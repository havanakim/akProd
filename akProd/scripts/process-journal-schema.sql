SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID(N'dbo.AKPROD_PROCESS_JOURNAL',N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AKPROD_PROCESS_JOURNAL (
        REQUEST_ID varchar(36) NOT NULL CONSTRAINT PK_AKPROD_PROCESS_JOURNAL PRIMARY KEY,
        USER_ID nvarchar(100) NOT NULL,
        MACHINE_NO nvarchar(50) NOT NULL,
        WORK_DATE date NOT NULL,
        CAPTURED_AT datetime2(3) NOT NULL,
        VALUES_JSON nvarchar(max) NOT NULL CONSTRAINT CK_AKPROD_JOURNAL_JSON CHECK(ISJSON(VALUES_JSON)=1),
        OCR_TEXT nvarchar(max) NOT NULL,
        PHOTO_JPEG varbinary(max) NOT NULL,
        PAYLOAD_SHA256 char(64) NOT NULL,
        CREATED_AT datetime2(3) NOT NULL CONSTRAINT DF_AKPROD_JOURNAL_CREATED DEFAULT SYSDATETIME(),
        CONSTRAINT CK_AKPROD_JOURNAL_PHOTO CHECK(DATALENGTH(PHOTO_JPEG) BETWEEN 4 AND 8000000)
    );
    CREATE INDEX IX_AKPROD_JOURNAL_SEARCH ON dbo.AKPROD_PROCESS_JOURNAL(USER_ID,WORK_DATE DESC,REQUEST_ID DESC) INCLUDE(MACHINE_NO);
END;
COMMIT TRANSACTION;
